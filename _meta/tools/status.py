# ----- small helpers ---------------------------------------------------------
def _stamp(fm: dict, *keys) -> dt.datetime | None:
    """The first parsable timestamp among `keys`, else generated.at."""
    gen = fm.get("generated") or {}
    for value in [fm.get(k) for k in keys] + [gen.get("at") if isinstance(gen, dict) else None]:
        if value:
            try:
                return pages.parse_iso(value)
            except (ValueError, TypeError):
                continue
    return None


def _read_pages(base: Path):
    for path in sorted(base.rglob("*.md")) if base.is_dir() else []:
        if pages.is_page_path(path):
            try:
                fm, body = pages.read(path)
            except Exception:
                continue
            if fm:
                yield path, fm, body


def _jsonl(path: Path) -> list:
    out = []
    for line in path.read_text(encoding="utf-8", errors="replace").splitlines() if path.is_file() else []:
        if line.strip() and not line.lstrip().startswith("#"):
            try:
                out.append(json.loads(line))
            except ValueError:
                continue
    return out


def _template(root: Path, name: str) -> str:
    for path in (root / "_meta" / "templates" / name, TEMPLATES / name):
        if path.is_file():
            return path.read_text(encoding="utf-8").replace("\r\n", "\n")
    raise FileNotFoundError(f"no template {name} under {root} or {TEMPLATES}")


def _slug_title(slug: str) -> str:
    return " ".join(part.capitalize() for part in slug.split("-") if part)


def _lines(items) -> str:
    return "\n".join(e.line() for e in items) or "- none"


def _newest(items):
    return sorted(items, key=lambda e: (e.at, e.title), reverse=True)


def _count_md(folder: Path) -> int:
    return len(list(folder.glob("*.md"))) if folder.is_dir() else 0


def _current(path: Path) -> str | None:
    return path.read_text(encoding="utf-8").replace("\r\n", "\n") if path.is_file() else None


def _without_stamp(text: str) -> str:
    return "\n".join(l for l in text.split("\n") if not l.startswith("generated:"))


def _snapshot_fm(root: Path, rel: str, title: str, now) -> dict:
    """Frontmatter for a generated snapshot page; the id is kept across runs."""
    pid = None
    if (root / rel).is_file():
        try:
            pid = str(pages.read(root / rel)[0].get("id") or "")
        except Exception:
            pid = None
    pid = pid if pid and pages.ID_RE.match(pid) else pages.new_id()
    return {"id": pid, "type": "snapshot", "title": title, "status": "draft",
            "generated": pages.generated("status", now)}


def _mtime(path: Path, now: dt.datetime) -> dt.datetime:
    stamps = [path.stat().st_mtime] + [p.stat().st_mtime for p in path.rglob("*") if p.is_file()]
    return min(dt.datetime.fromtimestamp(max(stamps), dt.timezone.utc).replace(microsecond=0), now)


# ----- (a) the desk ----------------------------------------------------------
def _register_desk(root: Path, space, reg, now) -> tuple[list, list]:
    registered, skipped = [], []
    for kind_dir in sorted((root / "work").iterdir()) if (root / "work").is_dir() else []:
        if not kind_dir.is_dir() or kind_dir.name not in space.kinds:
            continue
        for folder in sorted(p for p in kind_dir.iterdir() if p.is_dir()):
            if reg.get(folder.name) is not None:
                continue
            if not SLUG_RE.match(folder.name):
                skipped.append(f"work/{kind_dir.name}/{folder.name}/: not a lowercase slug")
                continue
            reg.add({"id": folder.name, "kind": kind_dir.name, "title": _slug_title(folder.name)},
                    by="librarian", now=now)
            registered.append(folder.name)
    return registered, skipped


# ----- evidence ---------------------------------------------------------------
def collect(root: Path, space, reg, now) -> dict:
    """subject id -> evidence found in this space: witness pages, candidates, pages, desk."""
    scope = SCOPE.get(space.profile, "mine")
    known = {s.id for s in reg.everywhere()}
    found: dict = {}

    seen: set = set()

    def add(sid, tier, scope_, title, at, rel="", pid="", text="", section="timeline", ptype="",
            status="", arrived=None, direction="", item=0):
        if (sid, section, title, at) in seen:   # one record witnessed twice shows once
            return
        seen.add((sid, section, title, at))
        found.setdefault(sid, []).append(Evidence(sid, tier, scope_, title, at, rel, pid, text,
                                                  section, ptype, status, arrived, direction, item))

    own = _own_domains(space, reg)
    threads: dict = {}
    closed = _closed(root)
    informed = []   # pages whose router said what they inform: their open items replace the thread's
    for path, fm, body in _read_pages(root / "knowledge" / "sources"):
        at = _stamp(fm, "at")
        # evidence attaches by identifier or by a routing decision, wherever the route went (the
        # record is this space's own); a mention alone stays out
        sids = [s for s in registry_mod.routed_subjects(fm, None) if s in known]
        if not sids or at is None or pages.withdrawn(fm):
            continue
        rel, pid, title = path.relative_to(root).as_posix(), str(fm.get("id") or ""), str(fm.get("title") or path.stem)
        tier = "system" if _is_system(fm, space) else "witness"
        state = str(fm.get("state") or "").lower()
        routing = fm.get("routing") if isinstance(fm.get("routing"), dict) else {}
        # the router's reading: what it informs here (`informs`) and elsewhere (`routing.informs`,
        # kept apart so distill never turns it into a second candidate); its projections' ids
        # stand for the record when a later route closes one
        informs = [i for i in list(fm.get("informs") or []) + list(routing.get("informs") or [])
                   if isinstance(i, dict)]
        if informs:
            refs = {pid} | {str(x) for x in routing.get("items") or []}
            informed.append((sids, at, tier, rel, pid, body, informs, _thread_of(fm, title), refs))
        # a record the router decided holds its thread with no guessed direction
        read = bool(informs) or routing.get("decision") in ("route", "private")
        for sid in sids:
            if fm.get("issue") and state in DONE_STATES:
                add(sid, tier, scope, title, at, rel, pid, body, "closed", arrived=_stamp(fm))
                add(sid, tier, scope, title, at, rel, pid, body, arrived=_stamp(fm))   # and on the timeline
                continue
            add(sid, tier, scope, title, at, rel, pid, body, arrived=_stamp(fm))
            key, direction = (sid, _thread_of(fm, title)), "" if read else _direction(fm, own)
            last = threads.get(key)
            # the newest record holds the thread; at the same moment, the one that knows who moves next
            if last is None or at > last[0] or (at == last[0] and direction and not last[6]):
                threads[key] = (at, tier, title, rel, pid, body, direction)
    # a later route names an item by the id on its line: `closes` when it settled the item,
    # `replaces` when it restates the item (a new date, owner or step) and takes its place
    closes, replaces = ({str(i[key]) for *_, informs, _, _ in informed for i in informs if i.get(key)}
                        for key in ("closes", "replaces"))
    routed_since = now - space.scale(OPEN_DAYS * 24)
    for sids, at, tier, rel, pid, body, informs, thread, refs in informed:
        for sid in sids:
            items = [i for i in informs if i.get("kind") == "open_item"
                     and not (i.get("subject") and str(i["subject"]) != sid)]   # informs one subject only
            for n, item in enumerate(items, 1):
                names = refs | {f"{r}.{n}" for r in refs}   # the whole record, or this item of it
                label = _informs_label(item)
                direction = str(item.get("direction") or "internal")
                direction = direction if direction in DIRECTIONS else "internal"
                said = closed.get((sid, thread))
                if names & closes or (said and at <= said[0]):   # a later record, or the person, closed it
                    add(sid, tier, scope, label, at, rel, pid, body, "closed")
                elif names & replaces:
                    continue
                elif at >= routed_since:
                    add(sid, tier, scope, label, at, rel, pid, body, "open", direction=direction,
                        item=n if len(items) > 1 else 0)
    open_since = now - space.scale(OPEN_DAYS * 24)
    for (sid, thread), (at, tier, title, rel, pid, body, direction) in threads.items():
        said = closed.get((sid, thread))
        if said and at <= said[0]:   # the person said so; a newer record opens it again
            add(sid, tier, scope, f"{title} ({said[1]} by {said[2]})", said[0], rel, pid, body, "closed")
            continue
        if direction and at >= open_since:
            add(sid, tier, scope, title, at, rel, pid, body, "open", direction=direction)
    for path, fm, body in _read_pages(root / "_inbound" / "candidates"):
        sid, at = str(fm.get("subject") or ""), _stamp(fm)
        if sid not in known or at is None:
            continue
        rel, title, pid = path.relative_to(root).as_posix(), str(fm.get("title") or path.stem), str(fm.get("id") or "")
        if fm.get("released_from"):   # a landed record from another space
            add(sid, "pending", "team", title, at, rel, pid, body, "open")
            add(sid, "reported", "team", title, at, rel, pid, body)
        else:
            add(sid, "pending", scope, title, at, rel, pid, body, "open")
    for kind in space.kinds:
        base = root / "knowledge" / kind
        for path, fm, body in _read_pages(base):
            parts = path.relative_to(base).parts
            stable = str(fm.get("status") or "") == "stable"
            at = _stamp(fm, "signed_at") if stable else _stamp(fm)
            if len(parts) >= 2 and parts[0] in known and at is not None:
                add(parts[0], "signed" if stable else "working", scope, str(fm.get("title") or path.stem),
                    at, path.relative_to(root).as_posix(), str(fm.get("id") or ""), body,
                    "closed" if stable else "timeline", str(fm.get("type") or ""), str(fm.get("status") or ""))
    for kind_dir in sorted((root / "work").iterdir()) if (root / "work").is_dir() else []:
        if not kind_dir.is_dir() or kind_dir.name not in space.kinds:
            continue
        for folder in sorted(p for p in kind_dir.iterdir() if p.is_dir() and p.name in known):
            for effort in sorted(p for p in folder.iterdir() if p.is_dir()) or [folder]:
                rel = effort.relative_to(root).as_posix()
                add(folder.name, "working", scope, rel, _mtime(effort, now), rel)
    return found


CLOSED = Path("_meta") / "state" / "status-closed.jsonl"
CLOSE_AS = ("done", "unrelated", "dropped")


def _closed(root: Path) -> dict:
    """(subject, thread) -> (when, as, by) for the items a person said are done."""
    out: dict = {}
    for row in _jsonl(Path(root) / CLOSED):
        try:
            key = (str(row["subject"]), str(row["thread"]))
            out[key] = (pages.parse_iso(row["at"]), str(row.get("as") or "done"), str(row.get("by") or "the owner"))
        except (KeyError, TypeError, ValueError):
            continue
    return out


def close(root, subject: str, page_id: str, as_: str = "done", by: str | None = None,
          now: dt.datetime | None = None) -> str:
    """Close the thread a status item stands for, on the person's word ("item 2 is done", "not
    related", "drop it"). The status page is generated; this is the one way to change what it
    lists. Returns the thread; ValueError when no evidence page has that id."""
    root = Path(root)
    if as_ not in CLOSE_AS:
        raise ValueError(f"as is one of {', '.join(CLOSE_AS)}")
    space = spaceyaml.load(root)
    now = now or space.now()
    page_id = re.sub(r"\.\d+$", "", page_id)   # one item of several (`<id>.<n>`): the person closes its thread
    for path, fm, body in _read_pages(root / "knowledge" / "sources"):
        if str(fm.get("id") or "") == page_id or str(fm.get("record") or "") == page_id:
            thread = _thread_of(fm, str(fm.get("title") or path.stem))
            CLOSED.parent.mkdir(parents=True, exist_ok=True) if False else None
            target = root / CLOSED
            target.parent.mkdir(parents=True, exist_ok=True)
            with target.open("a", encoding="utf-8", newline="\n") as fh:
                fh.write(json.dumps({"at": pages.iso(now), "subject": subject, "thread": thread,
                                     "page": page_id, "as": as_, "by": by or space.owner or "the owner"}) + "\n")
            return thread
    raise ValueError(f"no evidence page with id {page_id}")


def _see_also(root: Path) -> dict:
    """subject id -> pages named by question-log entries that needed steering."""
    out: dict = {}
    for entry in _jsonl(root / "_meta" / "questions.log"):
        if isinstance(entry, dict) and entry.get("needed_steering") and entry.get("subject"):
            bucket = out.setdefault(str(entry["subject"]), [])
            bucket.extend(str(p) for p in entry.get("pages") or [] if str(p) not in bucket)
    return out


# ----- renderers --------------------------------------------------------------
OPEN_DAYS = 14
DONE_STATES = {"done", "closed", "completed", "canceled", "cancelled", "duplicate", "merged"}
DIRECTIONS = ("we owe", "waiting on them", "internal")
AUTOMATED = re.compile(r"^(no[-_.]?reply|do[-_.]?not[-_.]?reply|notifications?|mailer-daemon|postmaster|bounces?)[-_.+@]")


def _informs_label(item: dict) -> str:
    """An open item as the router wrote it, with its owner and due date when it has them."""
    extra = [f"owner {item['owner']}" if item.get("owner") else "", f"due {item['due']}" if item.get("due") else ""]
    extra = ", ".join(x for x in extra if x)
    return str(item.get("text") or "").strip() + (f" ({extra})" if extra else "")


def _domain(address) -> str:
    text = str(address or "").strip().lower()
    text = text.split("<")[-1].rstrip(">").strip() if "<" in text else text
    return text.split("@")[1] if "@" in text else ""


def _is_system(fm: dict, space) -> bool:
    """System-tier evidence: the tracker, merged code, and mail this space's person sent."""
    if fm.get("issue") or str(fm.get("source") or "") in ("tracker", "code", "repo", "repository"):
        return True
    own = _domain(space.owner_email)
    return fm.get("kind") == "mail" and bool(own) and \
        str(fm.get("from") or "").strip().lower().split("<")[-1].rstrip(">").strip() == space.owner_email.strip().lower()


def _thread_of(fm: dict, title: str) -> str:
    ident = fm.get("identifiers") or {}
    if isinstance(ident, dict) and ident.get("thread"):
        return str(ident["thread"])
    if fm.get("issue"):
        return f"issue:{fm['issue']}"
    return re.sub(r"^(\s*(re|fwd?|aw|wg)\s*:\s*)+", "", title.strip().lower())


def _own_domains(space, reg) -> set:
    """Our mail domains: the owner's and every registered colleague's (email and any address
    among their aliases), so a reply from a second company domain is still ours."""
    own = {_domain(space.owner_email)}
    for person in reg.everywhere():
        if person.kind == "people":
            own |= {_domain(a) for a in [person.extra.get("email"), *person.aliases] if a}
    return own - {""}


def _direction(fm: dict, own) -> str:
    """Who holds the next move on a thread, from its last record."""
    own = {own} if isinstance(own, str) else set(own or ())
    own.discard("")
    if fm.get("issue"):
        return "internal"
    if fm.get("kind") not in ("mail", "message") or not own:
        return ""
    if AUTOMATED.match(registry_mod.address_of(fm.get("from"))):   # a notice holds no next move
        return ""
    sender = _domain(fm.get("from"))
    if not sender:
        return ""
    if sender not in own:
        return "we owe"
    others = [_domain(t) for t in (fm.get("to") or [])]
    return "waiting on them" if any(d and d not in own for d in others) else "internal"


def _open_text(evs: list) -> str:
    """Open items by direction, then what waits for a signature."""
    parts = []
    for direction in DIRECTIONS:
        lines = _newest(e for e in evs if e.section == "open" and e.direction == direction)
        if lines:
            parts.append(f"### {direction[0].upper()}{direction[1:]}\n\n" + _lines(lines))
    pending = _newest(e for e in evs if e.section == "open" and not e.direction)
    if pending:
        parts.append("### Waiting for a signature\n\n" + _lines(pending))
    return "\n\n".join(parts) or "- none"


def _render_status(space, subject, evs: list, now, template: str) -> str:
    cut, today = now - space.scale(CLOSED_HOURS), f"{now:%Y-%m-%d}"
    coming: dict = {}
    for e in _newest(evs):
        for day in DATE_RE.findall(f"{e.title}\n{e.text}"):
            try:
                dt.date.fromisoformat(day)
            except ValueError:
                continue
            if day > today:
                coming.setdefault((day, e.title), f"- {day}: {e.title} ({e.tier}, {e.scope}, {e.at:%Y-%m-%d})")
    ahead = [e for e in evs if e.section == "timeline" and e.at > now]   # a calendar event not yet held
    for e in ahead:
        day = f"{e.at:%Y-%m-%d}"
        coming.setdefault((day, e.title), f"- {day}: {e.title} ({e.tier}, {e.scope}, {day})")
    text = template.format(
        title=f"{subject.title}: status", subject=subject.id,
        open=_open_text(evs),
        closed=_lines(_newest(e for e in evs if e.section == "closed" and e.at >= cut)),
        timeline=_lines(_newest(e for e in evs if e.section == "timeline" and e not in ahead)[:TIMELINE_LINES]),
        coming="\n".join(coming[k] for k in sorted(coming)) or "- none")
    found = pointers(evs)
    if not found:
        return text
    import link
    lines = "".join(f"- [{ref}]({link.ref_url(ref)})\n" for ref in found)
    return text.rstrip("\n") + "\n\n## Pointers\n\n" + lines


def pointers(evs: list, limit: int = 10) -> list:
    """The `ref:` pointers into code that the subject's witness and landed pages under
    knowledge/sources/ carry (landing files records there), newest first, each once. Only the
    pointer forms count, so a mail's `Ref: <number>` line is no pointer."""
    import link
    found = [ref for e in _newest(e for e in evs if e.path.startswith("knowledge/sources/"))
             for ref in link.refs_in(e.text) if link.ref_url(ref)]
    return list(dict.fromkeys(found))[:limit]


def _see_link(page: str, fresh: dict) -> str:
    path = fresh.get(page) if pages.ID_RE.match(page) else None
    if path is None:
        return f"`{page}`"
    try:
        return f"[{pages.read(path)[0].get('title') or page}](id:{page})"
    except Exception:
        return f"[{page}](id:{page})"


def _render_hub(reg, subject, evs: list, status_id, see_also: list, fresh: dict) -> str:
    folder = f"knowledge/{subject.kind}/{subject.id}/"
    items = [f"- [{e.title}](id:{e.id}) ({e.status}, {e.ptype})"
             for e in sorted((e for e in evs if e.path.startswith(folder) and e.id),
                             key=lambda e: (e.status != "stable", e.title.lower()))]
    if status_id:
        items.append(f"- Status: [status](id:{status_id})")
    for e in _newest(e for e in evs if e.section == "open"):
        label = f"[{e.title}](id:{e.id})" if e.id else e.title
        items.append(f"- Pending: {label} ({e.tier}, {e.scope}, {e.at:%Y-%m-%d})")
    items += [f"- Part of: {u.title}" for u in reg.ancestors_of(subject.id)]
    if see_also:
        items.append("- See also: " + ", ".join(_see_link(p, fresh) for p in see_also))
    body = (f"# {subject.title}\n\nHub for subject `{subject.id}` ({subject.kind}, {subject.state}). "
            f"Links only. {NOTE}\n\n" + "\n".join(items or ["- No pages yet."]) + "\n")
    return pages.render({"title": subject.title}, body)


