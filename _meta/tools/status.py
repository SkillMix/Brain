# ----- small helpers ---------------------------------------------------------
def _stamp(fm: dict, *keys) -> dt.datetime | None:
    """The first parsable timestamp among `keys`, else generated.at."""
    gen = fm.get("generated") or {}
    for value in [fm.get(k) for k in keys] + [gen.get("at") if isinstance(gen, dict) else None]:
        if value:
            try:
                return pages.parse_iso(value)
            except (ValueError, TypeError):
                continue
    return None


def _read_pages(base: Path):
    for path in sorted(base.rglob("*.md")) if base.is_dir() else []:
        if pages.is_page_path(path):
            try:
                fm, body = pages.read(path)
            except Exception:
                continue
            if fm:
                yield path, fm, body


def _jsonl(path: Path) -> list:
    out = []
    for line in path.read_text(encoding="utf-8", errors="replace").splitlines() if path.is_file() else []:
        if line.strip() and not line.lstrip().startswith("#"):
            try:
                out.append(json.loads(line))
            except ValueError:
                continue
    return out


def _template(root: Path, name: str) -> str:
    for path in (root / "_meta" / "templates" / name, TEMPLATES / name):
        if path.is_file():
            return path.read_text(encoding="utf-8").replace("\r\n", "\n")
    raise FileNotFoundError(f"no template {name} under {root} or {TEMPLATES}")


def _slug_title(slug: str) -> str:
    return " ".join(part.capitalize() for part in slug.split("-") if part)


def _lines(items) -> str:
    return "\n".join(e.line() for e in items) or "- none"


def _newest(items):
    return sorted(items, key=lambda e: (e.at, e.title), reverse=True)


def _count_md(folder: Path) -> int:
    return len(list(folder.glob("*.md"))) if folder.is_dir() else 0


def _current(path: Path) -> str | None:
    return path.read_text(encoding="utf-8").replace("\r\n", "\n") if path.is_file() else None


def _without_stamp(text: str) -> str:
    return "\n".join(l for l in text.split("\n") if not l.startswith("generated:"))


def _snapshot_fm(root: Path, rel: str, title: str, now) -> dict:
    """Frontmatter for a generated snapshot page; the id is kept across runs."""
    pid = None
    if (root / rel).is_file():
        try:
            pid = str(pages.read(root / rel)[0].get("id") or "")
        except Exception:
            pid = None
    pid = pid if pid and pages.ID_RE.match(pid) else pages.new_id()
    return {"id": pid, "type": "snapshot", "title": title, "status": "draft",
            "generated": pages.generated("status", now)}


def _mtime(path: Path, now: dt.datetime) -> dt.datetime:
    stamps = [path.stat().st_mtime] + [p.stat().st_mtime for p in path.rglob("*") if p.is_file()]
    return min(dt.datetime.fromtimestamp(max(stamps), dt.timezone.utc).replace(microsecond=0), now)


# ----- (a) the desk ----------------------------------------------------------
def _register_desk(root: Path, space, reg, now) -> tuple[list, list]:
    registered, skipped = [], []
    for kind_dir in sorted((root / "work").iterdir()) if (root / "work").is_dir() else []:
        if not kind_dir.is_dir() or kind_dir.name not in space.kinds:
            continue
        for folder in sorted(p for p in kind_dir.iterdir() if p.is_dir()):
            if reg.get(folder.name) is not None:
                continue
            if not SLUG_RE.match(folder.name):
                skipped.append(f"work/{kind_dir.name}/{folder.name}/: not a lowercase slug")
                continue
            reg.add({"id": folder.name, "kind": kind_dir.name, "title": _slug_title(folder.name)},
                    by="librarian", now=now)
            registered.append(folder.name)
    return registered, skipped


# ----- evidence ---------------------------------------------------------------
def collect(root: Path, space, reg, now) -> dict:
    """subject id -> evidence found in this space: witness pages, candidates, pages, desk."""
    scope = SCOPE.get(space.profile, "mine")
    known = {s.id for s in reg.everywhere()}
    found: dict = {}

    def add(sid, tier, scope_, title, at, rel="", pid="", text="", section="timeline", ptype="",
            status="", arrived=None):
        found.setdefault(sid, []).append(Evidence(sid, tier, scope_, title, at, rel, pid, text,
                                                  section, ptype, status, arrived))

    for path, fm, body in _read_pages(root / "knowledge" / "sources"):
        at = _stamp(fm, "at")
        targets = [str(fm["subject"])] if fm.get("subject") else []
        targets += [str(m) for m in (fm.get("mentions") or []) if isinstance(fm.get("mentions"), list)]
        for sid in dict.fromkeys(t for t in targets if t in known and at is not None):
            add(sid, "witness", scope, str(fm.get("title") or path.stem), at,
                path.relative_to(root).as_posix(), str(fm.get("id") or ""), body, arrived=_stamp(fm))
    for path, fm, body in _read_pages(root / "_inbound" / "candidates"):
        sid, at = str(fm.get("subject") or ""), _stamp(fm)
        if sid not in known or at is None:
            continue
        rel, title, pid = path.relative_to(root).as_posix(), str(fm.get("title") or path.stem), str(fm.get("id") or "")
        if fm.get("released_from"):   # a landed record from another space
            add(sid, "pending", "team", title, at, rel, pid, body, "open")
            add(sid, "reported", "team", title, at, rel, pid, body)
        else:
            add(sid, "pending", scope, title, at, rel, pid, body, "open")
    for kind in space.kinds:
        base = root / "knowledge" / kind
        for path, fm, body in _read_pages(base):
            parts = path.relative_to(base).parts
            stable = str(fm.get("status") or "") == "stable"
            at = _stamp(fm, "signed_at") if stable else _stamp(fm)
            if len(parts) >= 2 and parts[0] in known and at is not None:
                add(parts[0], "signed" if stable else "working", scope, str(fm.get("title") or path.stem),
                    at, path.relative_to(root).as_posix(), str(fm.get("id") or ""), body,
                    "closed" if stable else "timeline", str(fm.get("type") or ""), str(fm.get("status") or ""))
    for kind_dir in sorted((root / "work").iterdir()) if (root / "work").is_dir() else []:
        if not kind_dir.is_dir() or kind_dir.name not in space.kinds:
            continue
        for folder in sorted(p for p in kind_dir.iterdir() if p.is_dir() and p.name in known):
            for effort in sorted(p for p in folder.iterdir() if p.is_dir()) or [folder]:
                rel = effort.relative_to(root).as_posix()
                add(folder.name, "working", scope, rel, _mtime(effort, now), rel)
    return found


def _see_also(root: Path) -> dict:
    """subject id -> pages named by question-log entries that needed steering."""
    out: dict = {}
    for entry in _jsonl(root / "_meta" / "questions.log"):
        if isinstance(entry, dict) and entry.get("needed_steering") and entry.get("subject"):
            bucket = out.setdefault(str(entry["subject"]), [])
            bucket.extend(str(p) for p in entry.get("pages") or [] if str(p) not in bucket)
    return out


# ----- renderers --------------------------------------------------------------
def _render_status(space, subject, evs: list, now, template: str) -> str:
    cut, today = now - space.scale(CLOSED_HOURS), f"{now:%Y-%m-%d}"
    coming: dict = {}
    for e in _newest(evs):
        for day in DATE_RE.findall(f"{e.title}\n{e.text}"):
            try:
                dt.date.fromisoformat(day)
            except ValueError:
                continue
            if day > today:
                coming.setdefault((day, e.title), f"- {day}: {e.title} ({e.tier}, {e.scope}, {e.at:%Y-%m-%d})")
    return template.format(
        title=f"{subject.title}: status", subject=subject.id,
        open=_lines(_newest(e for e in evs if e.section == "open")),
        closed=_lines(_newest(e for e in evs if e.section == "closed" and e.at >= cut)),
        timeline=_lines(_newest(e for e in evs if e.section == "timeline")[:TIMELINE_LINES]),
        coming="\n".join(coming[k] for k in sorted(coming)) or "- none")


def _see_link(page: str, fresh: dict) -> str:
    path = fresh.get(page) if pages.ID_RE.match(page) else None
    if path is None:
        return f"`{page}`"
    try:
        return f"[{pages.read(path)[0].get('title') or page}](id:{page})"
    except Exception:
        return f"[{page}](id:{page})"


def _render_hub(reg, subject, evs: list, status_id, see_also: list, fresh: dict) -> str:
    folder = f"knowledge/{subject.kind}/{subject.id}/"
    items = [f"- [{e.title}](id:{e.id}) ({e.status}, {e.ptype})"
             for e in sorted((e for e in evs if e.path.startswith(folder) and e.id),
                             key=lambda e: (e.status != "stable", e.title.lower()))]
    if status_id:
        items.append(f"- Status: [status](id:{status_id})")
    for e in _newest(e for e in evs if e.section == "open"):
        label = f"[{e.title}](id:{e.id})" if e.id else e.title
        items.append(f"- Pending: {label} ({e.tier}, {e.scope}, {e.at:%Y-%m-%d})")
    items += [f"- Part of: {u.title}" for u in reg.ancestors_of(subject.id)]
    if see_also:
        items.append("- See also: " + ", ".join(_see_link(p, fresh) for p in see_also))
    body = (f"# {subject.title}\n\nHub for subject `{subject.id}` ({subject.kind}, {subject.state}). "
            f"Links only. {NOTE}\n\n" + "\n".join(items or ["- No pages yet."]) + "\n")
    return pages.render({"title": subject.title}, body)


def _inherited(s, status_ids: dict) -> str:
    return f"{s.title} (inherited from {s.space}): [status](id:{status_ids[s.id]})"


def _by_title(subjects):
    return sorted(subjects, key=lambda s: s.title.lower())


def _render_kind_index(kind: str, own: list, inherited: list, status_ids: dict) -> str:
    lines = [f"- [{s.title}]({s.id}/index.md) ({s.state})" for s in _by_title(own)]
    lines += [f"- {_inherited(s, status_ids)}" for s in _by_title(inherited)]
    body = (f"# {_slug_title(kind)}\n\nOne line per subject of this kind. {NOTE}\n\n"
            + "\n".join(lines or ["- No subjects yet."]) + "\n")
    return pages.render({"title": _slug_title(kind)}, body)


def _subjects_block(by_kind: dict, status_ids: dict) -> list:
    lines = [SUBJECTS_MARKERS[0], "## Subjects", ""]
    for kind in sorted(by_kind):
        own, inherited = by_kind[kind]
        lines.append(f"- {kind} ([index](knowledge/{kind}/index.md))")
        lines += [f"  - [{s.title}](knowledge/{kind}/{s.id}/index.md) ({s.state})" for s in _by_title(own)]
        lines += [f"  - {_inherited(s, status_ids)}" for s in _by_title(inherited)]
    return lines + (["- No subjects yet."] if not by_kind else []) + [SUBJECTS_MARKERS[1]]


def _kinds_block(root: Path, space, by_kind: dict) -> list:
    lines = [KINDS_MARKERS[0]]
    for kind in space.kinds:
        n = sum(len(part) for part in by_kind.get(kind, ((), ())))
        lines.append(f"- [{kind}]({kind}/index.md): {n} subjects" if kind in by_kind
                     else f"- {kind}: no subjects yet")
    decisions = sum(1 for _ in _read_pages(root / "knowledge" / "decisions"))
    sources = sum(1 for _ in _read_pages(root / "knowledge" / "sources"))
    return lines + [f"- decisions (fixed): {decisions} pages", f"- sources (fixed): {sources} witness pages",
                    KINDS_MARKERS[1]]


def splice(text: str, markers: tuple, block: list) -> str:
    """Replace the lines between the markers (inclusive) with `block`; append when absent."""
    lines = text.replace("\r\n", "\n").split("\n")
    starts = [i for i, l in enumerate(lines) if l.strip() == markers[0]]
    ends = [i for i, l in enumerate(lines) if l.strip() == markers[1]]
    if starts and ends and ends[0] >= starts[0]:
        lines[starts[0]:ends[0] + 1] = block
    else:
        while lines and lines[-1] == "":
            lines.pop()
        lines += [""] + block
    return "\n".join(lines).rstrip("\n") + "\n"


def _probe_cell(root) -> str:
    try:
        import tests_run
    except ImportError:
        return "probe n/a"
    summary = tests_run.probe_summary(root)
    if summary is None:
        return "probe none yet"
    return "probe " + " ".join(f"{m} {c[0]}/{c[1]}" if c is not None else f"{m} n/a"
                               for m, c in summary.items())


def capture_rate(root, space, now) -> tuple[float, int] | None:
    """(captured share, sessions seen) over the last four scaled weeks, from the transcript
    adapter's `_meta/state/sessions.yaml`; None when nothing was seen."""
    path = Path(root) / SESSIONS
    if not path.exists():
        return None
    import yaml
    data = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
    rows = data.get("sessions") if isinstance(data, dict) else None
    since = now - space.scale(CAPTURE_DAYS * 24)
    seen = captured = 0
    for row in rows or []:
        stamp = _stamp(row, "start") if isinstance(row, dict) else None
        if stamp is None or stamp < since:
            continue
        seen += 1
        captured += bool(row.get("captured"))
    return (captured / seen, seen) if seen else None


def _requests_cell(root, space, now) -> str:
    since = now - space.scale(REQUEST_DAYS * 24)
    outcomes: dict = {}
    for row in _jsonl(Path(root) / REQUESTS_ASKED):
        try:
            at = pages.parse_iso(row.get("at"))
        except (TypeError, ValueError):
            continue
        if at >= since and row.get("id"):
            outcomes.setdefault(str(row["id"]), set()).add(str(row.get("outcome") or "asked"))
    asked = len(outcomes)
    answered = sum(1 for o in outcomes.values() if "answered" in o)
    expired = sum(1 for o in outcomes.values() if "expired" in o and "answered" not in o)
    cell = f"requests asked {asked} answered {answered} expired {expired}"
    held: dict = {}
    for row in _jsonl(Path(root) / "_meta" / "state" / "requests.jsonl"):
        try:
            at = pages.parse_iso(row.get("at"))
        except (TypeError, ValueError):
            continue
        if at >= since and row.get("id"):
            held.setdefault(str(row["id"]), set()).add(str(row.get("outcome") or ""))
    if held:
        cell += (f", received {len(held)} answered {sum(1 for o in held.values() if 'answered' in o)} "
                 f"expired {sum(1 for o in held.values() if 'expired' in o)}")
    return cell


