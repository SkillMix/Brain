# ----- the person's verdicts, and the librarian's own Needs-you items --------------------
# A person's answers are authority: request.py ships an answer and writes a standing choice on
# one, classify.py classifies on one, link.py links on one. So they are read from a store of
# their own that sign.py alone writes (`record_verdict`), never from what log.md says now: log.md
# is a narrative many tools append to, a routine may append to it, and a value with a line break
# in it (a page id another space sent) could start a line that reads like a verdict. A row of the
# store is one JSON object: {"at", "id", "by", "verb"} or {"at", "id", "by", "note"}.
#
# The cut-over. Before the store, sign.py's lines in log.md were the answers, and a space that
# upgrades keeps them: the store's first row (`pin_cutover`) holds a fingerprint of every verdict
# and note line log.md held when the store began: {"at", "cutover": "log.md", "fingerprints"}.
# Those lines, and only those, still count, each once at its first place in the log, below every
# row of the store. A line written after the cut-over is narrative whatever it reads like, also
# one that copies an earlier line word for word. Until the store begins no line counts: no store
# is no answer. The lines log.md holds when it begins are those the tools before the store already
# read as answers, so the pin adds none, and a routine on the computer may write it: the
# librarian's run (the daily chain runs it right after template sync), needs_you's list, the
# person's first answer through sign.py and the migration (`_meta/migrations/verdicts_cutover.py`,
# which template sync runs in a subprocess right after it lands new machinery) each pin it when
# there is no store yet, so it is pinned as soon after the upgrade as anything runs. A new space
# begins its store with an empty pin as soon as onboarding or mint writes its log.md
# (`onboard.begin_verdicts`). A cloud run never pins: its clone lands no store, and lines its own run wrote would join.
VERDICTS = Path("_meta") / "state" / "verdicts.jsonl"
VERDICT_VERBS = ("yes", "edit", "no", "always", "later")
LEGACY_NOTE_LINE = re.compile(r"^- (\S+) note (\S+) by ([^:]+): (.*)$")
LEGACY_VERDICT_LINE = re.compile(r"^- (\S+) (yes|edit|no|always|later) (\S+) by (.+)$")
CUTOVER = "log.md"


def _person(by) -> str:
    """The person a verdict is by, or "" when it names none: a routine never answers."""
    name = " ".join(str(by or "").split())
    return "" if not name or name.lower() == "routine" or name.lower().startswith("routine:") else name


def _routine_running() -> str | None:
    """Why this process runs inside a routine (`routine.in_routine`), or None. When that cannot
    be asked, the routine marker in the environment alone decides."""
    try:
        import routine
        return routine.in_routine()
    except Exception:   # noqa: BLE001 - fall back to the marker every routine command sees
        return "a routine runs this command" if os.environ.get("SPACES_ROUTINE") else None


def _in_cloud() -> bool:
    """A cloud run's marker is there (`cloud.state_path`, written by `cloud.py begin`), or the
    remote environment says so. When the marker cannot be looked for, the environment decides."""
    if os.environ.get("CLAUDE_CODE_REMOTE", "").lower() == "true":
        return True
    try:
        import cloud
        return cloud.state_path().exists()
    except Exception:   # noqa: BLE001 - a marker that cannot be looked for is no marker
        return False


def _fingerprint(line: str) -> str:
    return hashlib.sha256(line.encode("utf-8")).hexdigest()[:32]


def legacy_lines(root) -> list:
    """The verdict and note lines of log.md in the form sign.py wrote them before the store, in
    log order: (fingerprint, item id, {"verb" or "note", "by"}). A line naming no person (or a
    routine), or an id that is no record id, is none. Nothing is read through a link."""
    return _legacy_lines(root) or []


def _legacy_lines(root) -> list | None:
    """`legacy_lines`, or None when log.md is there but cannot be read safely (a link at it or at
    a folder above it, or a read that fails): then no pin is written, for a pin of nothing would
    drop every earlier answer for good. No log.md at all is no line."""
    lines = _log_lines(root)
    return None if lines is None else [(fp, item, value) for fp, _at, item, value in lines]


def _log_lines(root) -> list | None:
    """`_legacy_lines` with each line's time: (fingerprint, the time the line names, item id, value)."""
    log = Path(root) / "log.md"
    try:
        pages.check_no_links(log, root=Path(root))
        if pages.is_link(log):
            return None
        if not os.path.lexists(log):
            return []
        if not log.is_file():
            return None
        text = log.read_text(encoding="utf-8", errors="replace")
    except (OSError, pages.UnsafePath):
        return None
    out = []
    for line in text.splitlines():
        line = line.strip()
        found = LEGACY_NOTE_LINE.match(line)
        if found:
            item, value = found.group(2), {"note": found.group(4).strip(), "by": _person(found.group(3))}
        else:
            found = LEGACY_VERDICT_LINE.match(line)
            if not found:
                continue
            item, value = found.group(3), {"verb": found.group(2), "by": _person(found.group(4))}
        if value["by"] and pages.is_record_id(item):
            out.append((_fingerprint(line), found.group(1), item, value))
    return out


def _store(root) -> tuple:
    """(rows, state) of the verdict store: state is "absent", "unsafe" (reached through a link, or
    unreadable) or "present"; rows are the JSON objects it holds, in order."""
    path = Path(root) / VERDICTS
    try:   # never through a link, at the store or at a folder above it
        pages.check_no_links(path, root=Path(root))
        if pages.is_link(path):
            return [], "unsafe"
        if not os.path.lexists(path):
            return [], "absent"
        text = path.read_text(encoding="utf-8", errors="replace")
    except (OSError, pages.UnsafePath):
        return [], "unsafe"
    rows = []
    for line in text.splitlines():
        try:
            row = json.loads(line)
        except ValueError:
            continue
        if isinstance(row, dict):
            rows.append(row)
    return rows, "present"


def _pinned(rows: list) -> set:
    """The fingerprints of the log lines that still count: those any cut-over row names (two
    computers that each began the store before a merge give two rows, each pinning what that
    computer's log held)."""
    out: set = set()
    for row in rows:
        if row.get("cutover") == CUTOVER and isinstance(row.get("fingerprints"), list):
            out |= {f for f in row["fingerprints"] if isinstance(f, str)}
    return out


def pin_cutover(root, at=None) -> bool:
    """Begin the verdict store with its cut-over row when there is no store yet: the fingerprints
    of the verdict and note lines log.md holds now, which keep counting (see the note above). True
    when it wrote the row. A store already there, or a link in the way, is left as it is: the
    cut-over is pinned once and never moves, so a line written later never joins it. Nor is it
    pinned while log.md cannot be read safely (`_legacy_lines`): a pin of nothing would be for good. Safe in a
    routine on the computer: it records which earlier lines count and adds no answer. Never in a
    cloud run (`_in_cloud`): lines that run wrote itself would join the pin."""
    root = Path(root)
    path = root / VERDICTS
    if _in_cloud() or _store(root)[1] != "absent":
        return False
    lines = _legacy_lines(root)
    if lines is None:   # log.md through a link, or unreadable: a later run pins once it reads
        return False
    when = at if isinstance(at, dt.datetime) else dt.datetime.now(dt.timezone.utc)
    row = {"at": pages.iso(when), "cutover": CUTOVER,
           "fingerprints": sorted({fp for fp, _item, _value in lines})}
    try:
        pages.check_no_links(path, root=root)
        path.parent.mkdir(parents=True, exist_ok=True)
        fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL | getattr(os, "O_NOFOLLOW", 0)
                     | getattr(os, "O_BINARY", 0), 0o666)
    except FileExistsError:   # another process began it a moment ago: its row stands
        return False
    except (OSError, pages.UnsafePath):
        return False
    with open(fd, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(json.dumps(row, ensure_ascii=False) + "\n")
    return True


def cutover_state(root) -> dict:
    """Where this space stands with the cut-over: {"pinned": whether the store has begun, "kept":
    how many verdict or note lines of log.md count as answers (with no store yet: how many a pin
    now would keep), "after": how many log.md holds that do not}."""
    rows, state = _store(root)
    lines = legacy_lines(root)
    if state != "present":
        absent = state == "absent"
        return {"pinned": False, "kept": len({fp for fp, _i, _v in lines}) if absent else 0,
                "after": 0 if absent else len(lines)}
    pinned, seen = _pinned(rows), set()
    for fp, _item, _value in lines:
        if fp in pinned:
            seen.add(fp)
    kept = len(seen)
    return {"pinned": True, "kept": kept, "after": len(lines) - kept}


def record_verdict(root, item_id, by, verb=None, note=None, at=None) -> None:
    """Record one of a person's answers in the verdict store: a verb (`yes`, `edit`, `no`,
    `always`, `later`), a note, or both. sign.py calls it beside each verdict and note line it
    writes to log.md; no routine verb reaches it. Refused (ValueError): no person, a routine as
    `by`, a call made inside a routine (`routine.in_routine`: a routine never answers for the
    person, whichever tool it reached this through), an id that is empty or holds a control
    character, an unknown verb. The first answer into a space with no store pins the cut-over
    first (`pin_cutover`), so the answers given before the store keep counting."""
    person = _person(by)
    if not person:
        raise ValueError("a verdict is a named person's; routines never answer (rules.md section 1)")
    running = _routine_running()
    if running:
        raise ValueError(f"a verdict is a named person's, and {running}; routines never answer (rules.md section 1)")
    pages.check_record_id(item_id, what="item id")
    if verb is not None and verb not in VERDICT_VERBS:
        raise ValueError(f"a verdict is one of {', '.join(VERDICT_VERBS)} (got {verb!r})")
    if verb is None and note is None:
        raise ValueError("a verdict row carries a verb or a note")
    pin_cutover(root, at=at)
    row = {"at": pages.iso(at) if isinstance(at, dt.datetime) else str(at or ""), "id": item_id, "by": person}
    if verb is not None:
        row["verb"] = verb
    if note is not None:
        row["note"] = " ".join(str(note).split())   # one line, as the log's note line had it
    pages.append_text(Path(root) / VERDICTS, json.dumps(row, ensure_ascii=False) + "\n", root=Path(root))


def _apply(out: dict, item, value: dict) -> None:
    verb, note, person = value.get("verb"), value.get("note"), value.get("by")
    if verb is not None:
        out.setdefault(item, {}).update(verb=verb, by=person)
    if isinstance(note, str):
        out.setdefault(item, {}).update(note=note.strip(), by=person)


def verdicts(root) -> dict:
    """item id -> {"verb", "note", "by"}: the log.md lines the cut-over keeps (each once, in log
    order), then the rows of the verdict store sign.py writes (`record_verdict`), a later one over
    an earlier one. A row that is not an object, names no person (or a routine), has an id that is
    not a record id or a verb that is not one, is skipped. A store reached through a link gives no
    verdicts at all, and so does no store: until the cut-over is pinned (`pin_cutover`) a line in
    log.md answers nothing. A late line (`late_lines`) counts only once the person it names
    confirmed it: a `yes` or `always` row for `late-<its fingerprint>`, applied where that row stands."""
    rows, state = _store(root)
    out: dict = {}
    if state != "present":
        return out
    pinned, seen, late = _pinned(rows), set(), None
    for fp, item, value in legacy_lines(root) if pinned else ():
        if fp in pinned and fp not in seen:   # a copy written after the cut-over is no second answer
            seen.add(fp)
            _apply(out, item, value)
    for row in rows:
        item, person, verb, note = row.get("id"), _person(row.get("by")), row.get("verb"), row.get("note")
        if not pages.is_record_id(item) or not person:
            continue
        if verb is not None and verb not in VERDICT_VERBS:
            continue
        _apply(out, item, {"verb": verb, "note": note, "by": person})
        if str(item).startswith(LATE) and verb in CONFIRMS:   # the person confirmed a late line: it counts now
            late = late_lines(root, rows) if late is None else late
            found = late.get(str(item)[len(LATE):])
            if found and found[2]["by"].casefold() == person.casefold() and _late_shown(found[2]):
                _apply(out, found[1], found[2])
    return out


# ----- a late answer: a log.md line older tools wrote after the cut-over -------------------------
# A second computer still on the tools from before the store writes its answers to log.md only. Once
# the cut-over is pinned such a line never counts by itself (a line in log.md is narrative, and any
# tool's line could read like one), but it is not dropped either: each becomes one Needs-you item
# (`late_items`, on the librarian's file), "late-" and the line's fingerprint, asking whether the
# person it names gave that answer. Their yes, recorded in the store by sign.py like any answer, makes
# that exact line count (`verdicts`), bound by its fingerprint, and only when the one confirming is
# the person the line names; a no, or any other answer, closes the item and the line stays narrative.
LATE = "late-"
CONFIRMS = ("yes", "always")
LATE_NOTE_MAX = 500   # the longest late note shown whole on Needs you; a longer one is never confirmed here


def _late_shown(value: dict) -> bool:
    """Whether a late line's answer can be shown whole, exactly as it would count: a verb always; a note only when
    it is short enough (LATE_NOTE_MAX) and holds nothing the page would hide or change (`needs_you.untrusted_line`
    leaves it as it is). A yes then confirms what the person read and nothing past it."""
    import needs_you
    note = value.get("note")
    return note is None or (len(note) <= LATE_NOTE_MAX and needs_you.untrusted_line(note, None) == note)


def late_lines(root, rows=None) -> dict:
    """fingerprint -> (the time the line names, item id, value) of each verdict or note line of
    log.md, from a named person, that the cut-over did not pin and the store does not already hold:
    no row for that item of the same kind (a verb, a note), which is how sign.py's own narrative line
    beside each answer is told from an older tool's. Empty while the store has not begun (no answer
    counts then at all), and for an item that is itself a late one."""
    if rows is None:
        rows, state = _store(root)
        if state != "present":
            return {}
    if not any(row.get("cutover") == CUTOVER for row in rows):
        return {}
    pinned = _pinned(rows)
    held = {(str(row.get("id")), kind) for row in rows for kind in ("verb", "note")
            if row.get("id") and row.get(kind) is not None}
    out = {}
    for fp, at, item, value in _log_lines(root) or []:
        kind = "verb" if "verb" in value else "note"
        if fp in pinned or str(item).startswith(LATE) or (str(item), kind) in held:
            continue
        out.setdefault(fp, (at, item, value))
    return out


def late_items(root, given: dict) -> list:
    """One Needs-you item per late line (`late_lines`) not answered yet: whether the person it names
    gave that answer, naming the item answered by its text when an item of that id is on Needs you. A note is shown
    whole (`_late_shown`); one that cannot be is never confirmed here, and the item says to answer the first item
    again. Asked once: an answer of any kind but `later` closes it for good."""
    import needs_you
    out, asked = [], None
    for fp, (at, item, value) in late_lines(root).items():
        item_id = LATE + fp
        if item_id in given:
            continue
        if asked is None:
            asked = {i.id: i.text for i in needs_you.routine_items(Path(root))}
        who, shown = _inline(value["by"], 80), _late_shown(value)
        what = _inline(item, 120) + (f" (\"{_inline(asked[item], 160)}\")" if asked.get(item) else "")
        said = (f"answered {value['verb']}" if "verb" in value
                else f"added the note \"{_inline(value['note'], None)}\"" if shown
                else "added a note too long, or with characters, this page cannot show whole")
        ask = (f"Did {who} give this answer?" if shown
               else f"It cannot be confirmed here: if {who} gave it, {who} answers {_inline(item, 120)} again.")
        out.append({"id": item_id, "kind": "question",
                    "text": (f"log.md says {who} {said} to {what} ({_inline(at, 40)}). Older tools on "
                             f"another computer wrote it after this space began keeping answers in its verdict "
                             f"store, so it does not count yet. {ask}"),
                    "recommendation": (f"yes, if {who} gave it; no if nobody here did" if shown
                                       else f"no; {who} answers the item again"),
                    "default": "it does not count", "depends": 0, "for": value["by"],
                    "payload": json.dumps({"fingerprint": fp, "item": item, **value}, ensure_ascii=False)})
    return out


def _page_count(root: Path) -> int:
    return sum(1 for zone in ("knowledge", "live") for p in (root / zone).rglob("*.md")
               if (root / zone).is_dir() and pages.is_page_path(p))


def _ratio(cell) -> float:
    return cell[0] / cell[1] if cell and cell[1] else 0.0


def _index_item(root: Path, space, given: dict) -> dict | None:
    """A big project whose search finds more than the walk: one proposal for an index."""
    import search
    import tests_run
    item_id = f"index-{space.name}"
    if space.profile != "project" or search.config(root)["engine"] != "none":
        return None
    if item_id in given:
        return None
    summary = tests_run.probe_summary(root) or {}
    walk, found = summary.get("walk"), summary.get("search")
    count = _page_count(root)
    if count <= INDEX_PAGES or not walk or not found or _ratio(found) <= _ratio(walk):
        return None
    return {"id": item_id, "kind": "question",
            "text": (f"This space has {count} pages and search finds more than the walk "
                     f"({found[0]}/{found[1]} against {walk[0]}/{walk[1]}). Turn on an index for "
                     f"its own audience?"),
            "recommendation": "yes", "default": "plain search stays", "depends": 1}


def _apply_index(root: Path, verdict: dict) -> bool:
    if verdict.get("verb") not in ("yes", "always"):
        return False
    import search
    import yaml
    path = root / search.CONFIG
    data = yaml.safe_load(path.read_text(encoding="utf-8")) if path.exists() else None
    data = data if isinstance(data, dict) else {}
    data["engine"] = "index"
    pages.write_text(path, yaml.safe_dump(data, sort_keys=False), root=root)
    search.build(root)
    return True


def _probe_items(root: Path, given: dict) -> list:
    """Each question that needed steering, proposed once as a test question."""
    import hashlib
    import yaml
    known = set()
    answers = root / "_meta" / "tests" / "answers.yaml"
    if answers.exists():
        data = yaml.safe_load(answers.read_text(encoding="utf-8")) or {}
        known = {str(q.get("question")) for q in (data.get("questions") or []) if isinstance(q, dict)}
    out, seen = [], set()
    for entry in _jsonl(root / "_meta" / "questions.log"):
        if not isinstance(entry, dict) or not entry.get("needed_steering"):
            continue
        question = str(entry.get("question") or "").strip()
        if not question or question in known or question in seen:
            continue
        seen.add(question)
        item_id = "probe-q-" + hashlib.sha1(question.encode("utf-8")).hexdigest()[:8]
        if item_id in given:
            continue
        pages_used = ", ".join(str(p) for p in entry.get("pages") or []) or "none recorded"
        out.append({"id": item_id, "kind": "question",
                    "text": (f"Add \"{question}\" to this space's test questions? It needed steering; "
                             f"the pages that answered: {pages_used}."),
                    "recommendation": ("yes; edit with the facts the answer must contain, as the pages "
                                       "write them, separated by ;"),
                    "default": "not added", "depends": 0,
                    "payload": json.dumps({"question": question, "subject": entry.get("subject"),
                                           "pages": list(entry.get("pages") or [])})})
    return out


def _apply_probe(root: Path, item: dict, verdict: dict) -> dict | None:
    """Add the question with the facts given. A fact no page carries would fail the answer test
    from birth and block every landing: the question stays out, and the item returned asks again."""
    import yaml
    import tests_run
    if verdict.get("verb") not in ("yes", "edit", "always"):
        return None
    data = json.loads(item.get("payload") or "{}")
    facts = [f.strip() for f in str(verdict.get("note") or "").split(";") if f.strip()]
    if not facts:
        table = ids.known(root)
        for ref in data.get("pages") or []:
            rel = table.get(str(ref)) or str(ref)
            path = root / rel
            if path.is_file():
                facts.append(str(pages.read(path)[0].get("title") or path.stem))
    if not facts:
        return None
    question = {"question": data.get("question"), "subject": data.get("subject"),
                "expect": facts, "asker": "owner", "via": "both",
                "kind": "walk", "added_by": verdict.get("by") or "owner"}
    missing = tests_run.missing_facts(root, question)
    if missing:
        found = re.fullmatch(r"(probe-q-[0-9a-f]+)(?:-(\d+))?", str(item["id"]))
        base, attempt = (found.group(1), int(found.group(2) or 1)) if found else (str(item["id"]), 1)
        shown = "; ".join(f"\"{fact}\"" for fact in missing)
        return {"id": f"{base}-{attempt + 1}", "kind": "question",
                "text": (f"\"{data.get('question')}\" was not added to the test questions: no page the "
                         f"answer test reads carries {shown}. The test looks for each fact as a page writes "
                         f"it, under knowledge/, live/ or work/. Add it with such facts?"),
                "recommendation": ("edit with the facts as the pages write them, separated by ; "
                                   "(later, until a page carries them)"),
                "default": "not added", "depends": 0, "payload": item.get("payload")}
    path = root / "_meta" / "tests" / "answers.yaml"
    doc = yaml.safe_load(path.read_text(encoding="utf-8")) if path.exists() else None
    doc = doc if isinstance(doc, dict) else {}
    doc.setdefault("questions", []).append(question)
    pages.write_text(path, yaml.safe_dump(doc, sort_keys=False, allow_unicode=True), root=root)
    return None


def _transcripts_item(root: Path, space, now, given: dict) -> dict | None:
    """A personal space whose sessions are mostly not captured: propose the transcript switch."""
    cfg = space.data.get("transcripts") or {}
    if space.profile != "personal" or not isinstance(cfg, dict) or not cfg.get("path"):
        return None
    if str(cfg.get("switch", "off")).lower() in ("on", "true") or "transcripts-on" in given:
        return None
    rate = capture_rate(root, space, now)
    if rate is None or rate[1] < CAPTURE_MIN_SESSIONS or rate[0] >= CAPTURE_FLOOR:
        return None
    return {"id": "transcripts-on", "kind": "question",
            "text": (f"Only {rate[0]:.2f} of your last {rate[1]} sessions reached your daily notes. Turn on "
                     f"the transcript adapter, so missed sessions become evidence in your own space only?"),
            "recommendation": "yes", "default": "capture by instruction only", "depends": 1}


def _apply_transcripts(root: Path, space, verdict: dict) -> bool:
    if verdict.get("verb") not in ("yes", "always"):
        return False
    cfg = dict(space.data.get("transcripts") or {})
    cfg["switch"] = "on"
    space.data["transcripts"] = cfg
    spaceyaml.save(space)
    return True


def librarian_items(root: Path, space, reg, now, check: bool = False) -> tuple[str, list]:
    """The librarian's Needs-you file: apply verdicts on earlier items, then list what is new,
    a late answer to confirm among them (`late_items`). Returns (the file's text, the applied item
    ids)."""
    import yaml
    path = root / LIBRARIAN_ITEMS
    given = verdicts(root)
    old = yaml.safe_load(path.read_text(encoding="utf-8")) if path.exists() else None
    old_items = (old or {}).get("items") if isinstance(old, dict) else None
    applied, asked_again = [], []
    for item in old_items or []:
        verdict = given.get(str(item.get("id")))
        if not verdict or verdict.get("verb") in (None, "later") or check:
            continue
        if str(item["id"]).startswith("index-"):
            _apply_index(root, verdict)
        elif str(item["id"]).startswith("probe-q-"):
            again = _apply_probe(root, item, verdict)
            if again:
                asked_again.append(again)
        elif str(item["id"]).startswith("sample-"):
            import landing
            landing.apply_sample(root, item, verdict, now=now)
        elif str(item["id"]) == "transcripts-on":
            _apply_transcripts(root, space, verdict)
        applied.append(str(item["id"]))
    answered = {k for k, v in given.items() if v.get("verb") and v.get("verb") != "later"}
    current_unreachable = {f"reconnect-{s}" for s in unreachable_sources(root)}
    # measured proposals are recomputed every run: their numbers move, and one whose condition
    # no longer holds disappears
    recomputed = ("index-", "transcripts-on")
    items = [i for i in (old_items or []) if str(i.get("id")) not in answered
             and not str(i.get("id")).startswith(recomputed)
             and not (str(i.get("id")).startswith("reconnect-") and str(i.get("id")) not in current_unreachable)]
    have = {str(i.get("id")) for i in items}
    import landing
    fresh = ([_index_item(root, space, given), _transcripts_item(root, space, now, given)]
             + asked_again + _probe_items(root, given) + _reconnect_items(root, given) + late_items(root, given))
    if not any(str(i.get("id")).startswith("sample-") for i in items):
        fresh.append(landing.sample_item(root, space, reg, now, given))
    for new in fresh:
        if new and new["id"] not in have and new["id"] not in answered:
            items.append(new)
            have.add(new["id"])
    text = yaml.safe_dump({"items": items}, sort_keys=False, allow_unicode=True, width=100)
    return text, applied


# ----- signals that ask this space to pause a path; sources to reconnect ------------------
SIGNALS_IN = Path("_inbound") / "signals"
SIGNALS_READ = Path("_meta") / "state" / "signals-read.jsonl"
SWEEP_ROUTINES = ("sweep", "sweep-chain", "sweep_chain")


def read_signals(root: Path, space, now) -> list:
    """A `sample_failed` signal names an item this space released: pause the path that let it
    through, once per signal. Other signals only flag status pages and are left alone."""
    import release
    import yaml
    done = {str(r.get("id")) for r in _jsonl(root / SIGNALS_READ)}
    paused = []
    for path in sorted((root / SIGNALS_IN).glob("*.yaml")) if (root / SIGNALS_IN).is_dir() else []:
        try:
            data = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
        except Exception:
            continue
        if not isinstance(data, dict) or data.get("kind") != "sample_failed":
            continue
        sid = str(data.get("id") or path.stem)
        if sid in done:
            continue
        shipped = release.released_record(root, str(data.get("item") or ""))
        row = None
        path = release.path_of(shipped) if shipped else None
        if path:
            row = release.pause(root, path, now, "failed sample", str(data.get("item")), space)
        release.append_line(root / SIGNALS_READ, json.dumps({"id": sid, "at": pages.iso(now),
                                                             "item": data.get("item"),
                                                             "paused": (row or {}).get("path")}))
        if row:
            paused.append(row["path"])
    return paused


def moved_signals(root: Path, space, now) -> dict:
    """Content-free signals that an open item moved, from the last scaled week: subject ->
    (when, from which space). They flag the status page while the content waits its window."""
    import yaml
    out: dict = {}
    folder = root / SIGNALS_IN
    since = now - space.scale(7 * 24)
    for path in sorted(folder.glob("*.yaml")) if folder.is_dir() else []:
        try:
            data = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
            at = pages.parse_iso(data.get("at"))
        except Exception:
            continue
        if not isinstance(data, dict) or data.get("kind") in ("sample_failed", "registry") or not data.get("subject"):
            continue
        if since <= at <= now and (data["subject"] not in out or at > out[data["subject"]][0]):
            out[str(data["subject"])] = (at, str(data.get("from") or "another space"))
    return out


MINT_SIGNALS = Path("_inbound") / "needs-you" / "mint-signals.yaml"


def mint_signals(root: Path, space, reg, now) -> list:
    """When a wall is needed (vision section 4): a second regular reader (three answers to one
    asker about one subject in thirty scaled days), or a recurring group (the same two or more
    other people on five records of one subject homed here in thirty scaled days). Each is one
    proposal on Needs you, asked once."""
    import yaml
    since = now - space.scale(30 * 24)
    asked = (yaml.safe_load((root / MINT_SIGNALS).read_text(encoding="utf-8")) or {}) \
        if (root / MINT_SIGNALS).exists() else {}
    items = list(asked.get("items") or [])
    known = {i.get("id") for i in items}
    readers: dict = {}
    for row in _jsonl(root / "_meta" / "state" / "requests.jsonl"):
        try:
            if row.get("outcome") == "answered" and pages.parse_iso(row.get("at")) >= since:
                key = (str(row.get("from")), str(row.get("subject") or row.get("class")))
                readers[key] = readers.get(key, 0) + 1
        except (TypeError, ValueError):
            continue
    for (asker, what), n in sorted(readers.items()):
        sid = f"mint-signal-reader-{asker}-{what}"
        if n >= 3 and sid not in known:
            items.append({"id": sid, "kind": "question", "depends": 1,
                          "text": f"{asker} asked about {what} {n} times in a month: a second regular reader. "
                                  "Mint a space (a vault for a few names) that both read?",
                          "recommendation": "yes, if what they ask is not for everyone",
                          "default": "requests keep coming one by one"})
    groups: dict = {}
    own = {space.owner.strip().lower()}
    for path, fm, _ in _read_pages(root / "knowledge" / "sources"):
        sid = str(fm.get("subject") or "")
        if not sid or (reg.home_of(sid) or space.name) != space.name:
            continue
        try:
            if pages.parse_iso(fm.get("at")) < since:
                continue
        except (TypeError, ValueError):
            continue
        people = {str(p).strip().lower() for p in (fm.get("participants") or []) + (fm.get("to") or [])} - own
        people.discard(str(fm.get("from") or "").strip().lower())
        if len(people) >= 2:
            key = (sid, tuple(sorted(people)))
            groups[key] = groups.get(key, 0) + 1
    for (sid, people), n in sorted(groups.items()):
        gid = f"mint-signal-group-{sid}"
        if n >= 5 and gid not in known:
            items.append({"id": gid, "kind": "question", "depends": 1,
                          "text": f"The same people keep sharing {sid} with you ({len(people)} people, {n} records "
                                  "this month): a recurring group. Mint a space for it?",
                          "recommendation": "yes: python _meta/tools/mint.py with the desk seed and the crew",
                          "default": "it stays on your desk"})
            known.add(gid)
    if len(items) != len(asked.get("items") or []):
        pages.write_text(root / MINT_SIGNALS, yaml.safe_dump({"items": items}, sort_keys=False), root=root)
    return items


REGISTER_KINDS = (("projects", "Projects"), ("clients", "Clients"), ("deals", "Deals"))


def _period(period) -> str:
    if not isinstance(period, dict):
        return str(period or "")
    start, end = period.get("from"), period.get("to")
    if start and end:
        return f"{start} to {end}"
    return f"since {start}" if start else (f"until {end}" if end else "")


def _signed(root: Path, subject) -> bool:
    """A page with `status: stable` under the subject's knowledge/<kind>/<id>/."""
    folder = root / "knowledge" / subject.kind / subject.id
    return any(str(fm.get("status") or "") == "stable" for _, fm, _ in _read_pages(folder))


def _projects_page(root: Path, space, reg, moved: dict, now) -> str:
    """The brain's register of every project, client and deal, generated from the registry and
    each home: state, period, client, crew and work when known, "unconfirmed" while the subject
    has no signed page, owner and home, the last signal and the last landing. Nothing is kept
    by hand."""
    landed: dict = {}
    for row in _jsonl(root / "_meta" / "state" / "landed.jsonl"):
        sid = str(row.get("subject") or "")
        try:
            at = pages.parse_iso(row.get("at"))
        except (TypeError, ValueError):
            continue
        if sid and (sid not in landed or at > landed[sid]):
            landed[sid] = at

    def name(sid) -> str:
        known = reg.get(str(sid))
        return known.title if known is not None and known.title else str(sid)

    sections = []
    for kind, heading in REGISTER_KINDS:
        lines = []
        for s in sorted((s for s in reg.all() if s.kind == kind and s.state != "archived"),
                        key=lambda s: s.title.lower()):
            bits = [f"{s.state}"]
            if not _signed(root, s):
                bits.append("unconfirmed")
            if _period(s.period):
                bits.append(_period(s.period))
            if s.client:
                bits.append(f"client {name(s.client)}")
            if s.crew:
                bits.append("crew " + ", ".join(name(p) for p in s.crew))
            if s.work:
                bits.append(f"work: {s.work}")
            bits += [f"owner {reg.owner_of(s.id) or space.owner}", f"home {reg.home_of(s.id) or space.name}"]
            if s.id in moved:
                bits.append(f"last signal {moved[s.id][0]:%Y-%m-%d} from {moved[s.id][1]}")
            if s.id in landed:
                bits.append(f"last landing {landed[s.id]:%Y-%m-%d}")
            lines.append(f"- {_inline(s.title)} (`{s.id}`): " + "; ".join(bits))
        if lines:
            sections.append(f"## {heading}\n\n" + "\n".join(lines) + "\n")
    fm = _snapshot_fm(root, "live/projects.md", "Projects", now)
    body = ("# Projects\n\nThe register: one line per project, client and deal, generated from the "
            "registry and what each home sent (signals and landings): state, period, client, crew "
            "and work when known; unconfirmed until the subject has a signed page. Status lives at "
            "each subject's home.\n\n"
            + ("\n".join(sections) if sections else "- No projects, clients or deals yet.\n"))
    return pages.render(fm, body)


def unreachable_sources(root: Path) -> list:
    """The sources the newest agent sweep step could not reach (`notes.unreachable`)."""
    latest = None
    for row in _jsonl(root / "_meta" / "state" / "runs.jsonl"):
        notes = row.get("notes") if isinstance(row, dict) else None
        if row.get("routine") in SWEEP_ROUTINES and isinstance(notes, dict) and notes.get("step") == "agent":
            latest = notes
    if not latest:
        return []
    value = latest.get("unreachable") or []
    return sorted({str(v) for v in (value if isinstance(value, list) else [value]) if v})


def _reconnect_items(root: Path, given: dict) -> list:
    out = []
    for source in unreachable_sources(root):
        item_id = f"reconnect-{source}"
        if item_id in given:
            continue
        out.append({"id": item_id, "kind": "reconnect",
                    "text": f"Reconnect {source}: the last sweep could not reach it.",
                    "recommendation": "sign in again in your connector settings, then say yes",
                    "default": f"{source} is skipped until it is reachable", "depends": 1,
                    "check": "the next sweep run line no longer lists it as unreachable"})
    return out


# ----- spec state from the tracker (vision section 13) ----------------------------------
SPEC_STATES = {"backlog": "proposed", "triage": "proposed", "proposed": "proposed",
               "todo": "approved", "planned": "approved", "approved": "approved",
               "in progress": "building", "in review": "building", "started": "building",
               "done": "live", "completed": "live", "shipped": "live",
               "canceled": "superseded", "cancelled": "superseded", "duplicate": "superseded"}
SPEC_ZONES = ("knowledge", "work", "docs")


def spec_states(root: Path, now) -> list:
    """Set `state:` on every page with `tracker: <issue>` from the newest tracker record for
    that issue among the witness pages. Returns the pages changed."""
    newest: dict = {}
    for path, fm, _ in _read_pages(root / "knowledge" / "sources"):
        issue = fm.get("issue") or (fm.get("identifiers") or {}).get("issue")
        raw = str(fm.get("state") or "").strip().lower()
        stamp = _stamp(fm, "at")
        if issue and raw in SPEC_STATES and stamp is not None:
            if str(issue) not in newest or stamp > newest[str(issue)][0]:
                newest[str(issue)] = (stamp, SPEC_STATES[raw])
    changed = []
    for zone in SPEC_ZONES:
        base = root / zone
        if not base.is_dir():
            continue
        for path in sorted(base.rglob("*.md")):
            if "sources" in path.relative_to(root).parts or not pages.is_page_path(path):
                continue
            try:
                fm, body = pages.read(path)
            except Exception:
                continue
            issue = str(fm.get("tracker") or "")
            if not issue or issue not in newest or fm.get("state") == newest[issue][1]:
                continue
            fm["state"] = newest[issue][1]
            pages.write(path, fm, body, root=root)
            changed.append(path.relative_to(root).as_posix())
    return changed


def _weekly_probe(root: Path, space, now) -> bool:
    """The walk-and-search probe, once a scaled week, when the space has answer questions."""
    if not (root / "_meta" / "tests" / "answers.yaml").exists():
        return False
    try:
        import tests_run
    except ImportError:
        return False
    last = tests_run.last_probe(root)
    if last is not None:
        try:
            if now - pages.parse_iso(last.get("at")) < space.scale(PROBE_DAYS * 24):
                return False
        except (TypeError, ValueError):
            pass
    tests_run.probe(root, now=now)
    return True


# ----- the run ----------------------------------------------------------------
def run(root, now=None, check: bool = False) -> StatusReport:
    root = Path(root)
    if not check:
        pages.refuse_copy(root)
    space = spaceyaml.load(root)
    now = now or space.now()
    report = StatusReport()
    if not check:   # the verdict cut-over, first: from here on a new line in log.md is no answer
        pin_cutover(root, at=now)
    if space.profile == "channel":   # no knowledge, no live: nothing to reconcile
        if not check:
            _run_line(root, space, now, "channel: nothing to reconcile")
        return report
    if not check:
        report.probed = _weekly_probe(root, space, now)
        import classify   # registry notes before anything reads the registry
        classify.land_notes(root, space, now)
    reg = registry_mod.Registry(root, space)
    if not check:
        import landing
        report.landing = landing.land(root, space, reg, now)
        report.paused = read_signals(root, space, now)
        report.spec_states = spec_states(root, now)
        import librarian
        report.librarian = librarian.run(root, now=now)
        import decisions
        decisions.build(root)
        reg = registry_mod.Registry(root, space)
    items_text, report.applied = librarian_items(root, space, reg, now, check=check)
    if space.profile == "personal":
        report.registered, report.skipped = _register_desk(root, space, reg, now)
    evidence = collect(root, space, reg, now)
    # Dormancy: eight scaled weeks since evidence last ARRIVED here, judged only by the
    # space the subject's evidence lives in (its home, or the registering space). A subject
    # that never had evidence here is new, not dormant; content dates never count, since a
    # sweep may backfill old records. New evidence wakes it. A subject another registry holds
    # (the brain's, for a project or a person's topic) changes there by a note from its home.
    cutoff = now - space.scale(DORMANT_HOURS)
    held, held_changed = set(reg.subjects), False
    for subject in reg.all() + [s for s in reg.ancestors.values() if s.id not in held]:
        home = reg.home_of(subject.id)
        if (home and home != space.name) or (not home and subject.id not in held):
            continue
        arrivals = [e.arrived or e.at for e in evidence.get(subject.id, [])]
        if not arrivals:
            continue
        quiet = max(arrivals) < cutoff
        if subject.state == "active" and quiet:
            new, into = "dormant", report.dormant
        elif subject.state == "dormant" and not quiet:
            new, into = "active", report.woken
        else:
            continue
        subject.state = new
        into.append(subject.id)
        if subject.id in held:
            held_changed = True
        elif not check:
            import classify
            classify.send_state(root, subject.id, new, now)
    outputs: dict = {}
    template = _template(root, "status-page.md")
    status_ids: dict = {}
    moved = moved_signals(root, space, now)
    for subject in reg.everywhere():
        evs = evidence.get(subject.id)
        if (evs or subject.id in moved) and subject.stateful and subject.state != "archived":
            rel = f"live/subjects/{subject.id}.md"
            fm = _snapshot_fm(root, rel, f"{subject.title}: status", now)
            fm["subject"] = subject.id
            status_ids[subject.id] = fm["id"]
            text = _render_status(space, subject, evs or [], now, template)
            if subject.id in moved:
                at, origin = moved[subject.id]
                flag = (f"- News from {origin}: something here moved; the details follow once "
                        f"its review window ends (reported, team, {at:%Y-%m-%d})\n")
                text = text.replace("## Open\n\n", "## Open\n\n" + flag, 1)
            outputs[rel] = pages.render(fm, text)
            report.status_pages.append(rel)
    fresh = {pid: root / rel for pid, rel in ids.scan(root).items()}
    for ancestor in space.ancestor_roots():
        for pid, rel in ids.table(ancestor).items():
            fresh.setdefault(pid, ancestor / rel)
    see_also = _see_also(root)
    by_kind: dict = {}
    for subject in (s for s in reg.all() if s.state != "archived"):
        rel = f"knowledge/{subject.kind}/{subject.id}/index.md"
        outputs[rel] = _render_hub(reg, subject, evidence.get(subject.id, []),
                                   status_ids.get(subject.id), see_also.get(subject.id, []), fresh)
        report.hubs.append(rel)
        if subject.id in see_also:
            report.see_also[subject.id] = list(see_also[subject.id])
        by_kind.setdefault(subject.kind, ([], []))[0].append(subject)
    for subject in (s for s in reg.ancestors.values() if s.id in status_ids):
        by_kind.setdefault(subject.kind, ([], []))[1].append(subject)
    for kind, (own, inherited) in by_kind.items():
        outputs[f"knowledge/{kind}/index.md"] = _render_kind_index(kind, own, inherited, status_ids)
    if space.profile == "brain":
        outputs["live/projects.md"] = _projects_page(root, space, reg, moved, now)
    if not check and space.profile in ("personal", "project"):
        try:
            mint_signals(root, space, reg, now)
        except Exception:   # a proposal never stops the status pass
            pass
    outputs["index.md"] = splice(_current(root / "index.md") or DEFAULT_INDEX, SUBJECTS_MARKERS,
                                 _subjects_block(by_kind, status_ids))
    outputs["knowledge/index.md"] = splice(_current(root / "knowledge" / "index.md") or DEFAULT_KNOWLEDGE,
                                           KINDS_MARKERS, _kinds_block(root, space, by_kind))
    if not check:   # before the health line, so a --check right after a run agrees with it
        _run_line(root, space, now, f"registered {len(report.registered)}, status pages "
                  f"{len(report.status_pages)}, hubs {len(report.hubs)}, dormant {len(report.dormant)}")
    def mount_line(m: dict) -> str:
        # another space commits a mount's state: a file it broke never stops this space's health page
        try:
            return _health_line(space, str(m.get("name")), space.mount_root(str(m.get("name", ""))), now)
        except Exception as exc:
            return f"- {m.get('name')}: state unreadable ({type(exc).__name__})"
    report.health_lines = [_health_line(space, space.name, root, now)] + [mount_line(m) for m in space.mounts]
    report.health_lines += [f"- {rel} is a link; not written"
                            for rel in [*outputs, "live/health.md", "live/now.md"] if _link_in_way(root, rel)]
    door = unsure.health_line(root, _jsonl(root / "_meta" / "state" / "runs.jsonl"), now)   # counts only
    report.health_lines += [door] if door else []
    outputs["live/health.md"] = pages.render(
        _snapshot_fm(root, "live/health.md", "Health", now),
        "# Health\n\nOne line per space: this one, then each mount; then what the door settled by itself.\n\n"
        + "\n".join(report.health_lines) + "\n")
    outputs["live/now.md"] = pages.render(_snapshot_fm(root, "live/now.md", "Now", now),
                                          _render_now(root, space, reg, evidence, status_ids, now))
    if items_text.strip() != "items: []" or (root / LIBRARIAN_ITEMS).exists():
        outputs[LIBRARIAN_ITEMS.as_posix()] = items_text
    for rel, text in outputs.items():
        current = _current(root / rel)
        if current is None or _without_stamp(current) != _without_stamp(text):
            report.changed.append(rel)
        if not check and current != text:
            try:
                pages.write_text(root / rel, text, root=root)
            except pages.UnsafePath:   # a link where the page goes: named, never written through
                report.unwritten.append(f"{rel} is a link; not written")
    if report.registered or held_changed:
        if check:
            report.changed.append(registry_mod.REGISTRY_PATH.as_posix())
        else:
            reg.save()
    if not check:
        ids.build(root)
        _refresh_agents_md(root, report)
    return report


def _refresh_agents_md(root: Path, report) -> None:
    """The generated contract follows space.yaml and the template: rewrite it when stale (the
    status routine is the one writer of structure). So does the person's user-level instruction
    block, the only text a codebase session reads, where onboarding installed it for this space."""
    try:
        import agents_md
        if (root / "space.yaml").exists() and not agents_md.check(root):
            agents_md.write(root)
            report.changed.append("AGENTS.md")
        import onboard
        ui = Path.home() / ".claude" / "CLAUDE.md"
        if onboard.instruction_present(ui, root):
            onboard.install_instruction(ui, root)
    except Exception:  # a broken template must not stop the status pass
        pass


def main(argv=None) -> int:
    import needs_you
    needs_you.utf8_stdio()   # a page title in any script prints, never raises on a cp1252 pipe
    argv = sys.argv[1:] if argv is None else argv
    if len(argv) >= 4 and argv[1] == "close":   # status.py <root> close <subject> <page id> [--as X] [--by NAME]
        opts = dict(zip(argv[4::2], argv[5::2]))
        try:
            thread = close(Path(argv[0]), argv[2], argv[3], as_=opts.get("--as", "done"), by=opts.get("--by"))
        except ValueError as exc:
            print(str(exc), file=sys.stderr)
            return 1
        print(f"closed {argv[3]} on {argv[2]} ({opts.get('--as', 'done')}); thread {thread}")
        return 0
    check = "--check" in argv
    roots = [a for a in argv if not a.startswith("--")]
    report = run(Path(roots[0]) if roots else Path("."), check=check)
    if check:
        for rel in report.changed:
            print(f"would change: {rel}")
        print("up to date" if not report.changed else f"{len(report.changed)} file(s) would change")
        return 1 if report.changed else 0
    print(f"registered {len(report.registered)}, status pages {len(report.status_pages)}, "
          f"hubs {len(report.hubs)}, dormant {len(report.dormant)}, changed {len(report.changed)}")
    for note in report.skipped:
        print(f"skipped: {note}")
    for note in report.unwritten:
        print(f"not written: {note}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
