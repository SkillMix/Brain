def splice(text: str, markers: tuple, block: list) -> str:
    """Replace the lines between the markers (inclusive) with `block`; append when absent."""
    lines = text.replace("\r\n", "\n").split("\n")
    starts = [i for i, l in enumerate(lines) if l.strip() == markers[0]]
    ends = [i for i, l in enumerate(lines) if l.strip() == markers[1]]
    if starts and ends and ends[0] >= starts[0]:
        lines[starts[0]:ends[0] + 1] = block
    else:
        while lines and lines[-1] == "":
            lines.pop()
        lines += [""] + block
    return "\n".join(lines).rstrip("\n") + "\n"


